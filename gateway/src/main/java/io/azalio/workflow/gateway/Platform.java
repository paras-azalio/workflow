package io.azalio.workflow.gateway;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;
import java.util.stream.Stream;

/**
 * The platform files every project namespace needs - the launchers {@code bin/*.sh}, the wrapper jar, the JDBC driver -
 * shipped with the gateway (image folder {@code /app/platform}, same layout as in the namespace). A new project gets
 * them, a generated {@code config/<namespace>.properties} and KV {@code SHARED_DATA_DIR}; publishing a process does the
 * same (missing or changed platform files, a missing config or KV), so nobody uploads them by hand and a project made
 * before this existed catches up on its next publish.
 */
final class Platform {

    private final Kestra kestra;
    private final Path dir;
    private final String jdbcUrl;
    private final String jdbcUser;
    private final String sharedDataDir;

    Platform(Kestra kestra, Path dir, String jdbcUrl, String jdbcUser, String sharedDataDir) {
        this.kestra = kestra;
        this.dir = dir;
        this.jdbcUrl = jdbcUrl;
        this.jdbcUser = jdbcUser;
        this.sharedDataDir = sharedDataDir;
    }

    /** The platform files (missing or changed ones), the config (unless it has one) and SHARED_DATA_DIR (unless set). */
    List<String> provision(String namespace, String project) throws IOException, InterruptedException {
        List<String> done = sync(namespace);
        if (kestra.listNamespaceFiles(namespace, "/config").stream().noneMatch(f -> String.valueOf(f.get("path")).endsWith(".properties"))) {
            String path = "/config/" + namespace + ".properties";
            kestra.putNamespaceFile(namespace, path, config(project).getBytes(java.nio.charset.StandardCharsets.UTF_8));
            done.add(path.substring(1));
        }
        if (kestra.kv(namespace, "SHARED_DATA_DIR") == null) {
            kestra.putKv(namespace, "SHARED_DATA_DIR", sharedDataDir);
            done.add("KV SHARED_DATA_DIR");
        }
        return done;
    }

    /** Uploads the platform files the namespace lacks or holds in another version; the paths written. */
    List<String> sync(String namespace) throws IOException, InterruptedException {
        List<String> written = new ArrayList<>();
        for (Path file : files()) {
            String path = "/" + dir.relativize(file).toString().replace('\\', '/');
            byte[] wanted = Files.readAllBytes(file);
            if (!Arrays.equals(wanted, kestra.namespaceFileBytes(namespace, path))) {
                kestra.putNamespaceFile(namespace, path, wanted);
                written.add(path.substring(1));
            }
        }
        return written;
    }

    String config(String project) {
        return """
                # %s project config, generated by the gateway when the project was created. Edit it in Kestra (Namespaces -> Files).
                # The request store; its password comes from the Kestra secret CR_DB_PASSWORD, never from here.
                store.jdbc.url=%s
                store.jdbc.user=%s
                store.project=%s
                """.formatted(project, jdbcUrl, jdbcUser, project);
    }

    private List<Path> files() throws IOException {
        if (!Files.isDirectory(dir)) {
            throw new UserStore.Rejected(500, "The gateway has no platform files in %s (GATEWAY_PLATFORM_DIR).".formatted(dir));
        }
        try (Stream<Path> s = Files.walk(dir)) {
            return s.filter(Files::isRegularFile).sorted().toList();
        }
    }
}
