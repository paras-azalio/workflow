package com.nokia.workflow.gateway;

import com.nokia.workflow.wrapper.SimpleJson;

import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Set;

/**
 * "Try it" of a component version: runs one action with sample values in the project's namespace, through the
 * generated flow {@code cr_component_try} (deployed there when missing or outdated) and {@code bin/component.sh},
 * and answers what went in and what came out. Values reach the shell only through the environment.
 */
final class ComponentTry {

    static final String FLOW = "cr_component_try";
    private static final String MARK = "CR_TRY_RESULT ";
    private static final Set<String> FINISHED = Set.of("SUCCESS", "FAILED", "KILLED", "WARNING", "CANCELLED");

    private final Kestra kestra;

    ComponentTry(Kestra kestra) {
        this.kestra = kestra;
    }

    static String flowYaml(String namespace) {
        Map<String, Object> f = new LinkedHashMap<>();
        f.put("id", FLOW);
        f.put("namespace", namespace);
        f.put("description", "Try it of the Process designer's Components tab - generated by the gateway; it runs one action of a"
                + " component version with sample values.");
        f.put("labels", Map.of("generated", "true"));
        f.put("inputs", List.of(Map.of("id", "dir", "type", "STRING"), Map.of("id", "home", "type", "STRING"),
                Map.of("id", "action", "type", "STRING"), Map.of("id", "request", "type", "STRING")));
        Map<String, Object> task = new LinkedHashMap<>();
        task.put("id", "try");
        task.put("type", "io.kestra.plugin.scripts.shell.Commands");
        task.put("taskRunner", Map.of("type", "io.kestra.plugin.core.runner.Process"));
        task.put("namespaceFiles", Map.of("enabled", true, "include", List.of("bin/**", "wrappers/**", "lib/**", "config/**", "templates/**",
                "{{ inputs.dir }}/**", "{{ inputs.home }}/**")));
        Map<String, Object> env = new LinkedHashMap<>();
        env.put("SHARED_DATA_DIR", "{{ kv('SHARED_DATA_DIR', errorOnMissing=false) ?? '/mnt/shared_data' }}");
        env.put("ORDER_DIR", "try");
        env.put("DIR", "{{ inputs.dir }}");
        env.put("ACTION", "{{ inputs.action }}");
        env.put("REQUEST", "{{ inputs.request }}");
        task.put("env", env);
        task.put("commands", List.of(
                "printf '%s' \"$REQUEST\" > try-request.json",
                "sh bin/component.sh \"$DIR\" try --request try-request.json --param \"ACTION=$ACTION\"",
                "echo \"" + MARK.trim() + " $(tr -d '\\n' < out/try.result.json)\""));
        f.put("tasks", List.of(task));
        return PipelineCompiler.Yaml.write(f);
    }

    /** Runs the action and waits for it (at most {@code timeoutSec}): {state, result, log, execution_id}. */
    @SuppressWarnings("unchecked")
    Map<String, Object> run(String namespace, String dir, String home, String action, Map<String, Object> params, long timeoutSec)
            throws Exception {
        String yaml = flowYaml(namespace);
        List<String> problems = kestra.validateFlow(yaml);
        if (!problems.isEmpty()) {
            throw new UserStore.Rejected(500, "The try flow is not valid in Kestra: " + String.join("; ", problems));
        }
        kestra.deployFlow(namespace, FLOW, yaml);
        Map<String, String> request = new LinkedHashMap<>();
        params.forEach((k, v) -> request.put(k, v == null ? "" : String.valueOf(v)));
        Map<String, Object> e = kestra.startExecution(namespace, FLOW, List.of("component_try:" + dir.replace('/', '.')),
                Map.of("dir", dir, "home", home, "action", action, "request", SimpleJson.writeCompact(request)), Map.of());
        String id = String.valueOf(e.get("id"));
        long until = System.currentTimeMillis() + (timeoutSec + 120) * 1000;
        String state = null;
        while (System.currentTimeMillis() < until) {
            state = kestra.executionState(id);
            if (state != null && FINISHED.contains(state)) {
                break;
            }
            Thread.sleep(1500);
        }
        List<String> log = kestra.executionLogs(id);
        Object result = null;
        List<String> shown = new ArrayList<>();
        for (String line : log) {
            if (line.startsWith(MARK)) {
                try {
                    result = SimpleJson.parse(line.substring(MARK.length()));
                } catch (RuntimeException ignored) {
                    shown.add(line);
                }
            } else {
                shown.add(line);
            }
        }
        Map<String, Object> out = new LinkedHashMap<>();
        out.put("execution_id", id);
        out.put("state", state == null ? "UNKNOWN" : state);
        out.put("result", result instanceof Map ? result : null);
        out.put("log", shown.size() > 400 ? shown.subList(shown.size() - 400, shown.size()) : shown);
        return out;
    }
}
